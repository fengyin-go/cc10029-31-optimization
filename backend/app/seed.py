def _manifest_rows(snapshots: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """归档批次清单台账：与快照同一事务同步，区段与原落地记录一一对应。"""
    rows: list[dict[str, Any]] = []
    for snapshot in snapshots:
        for seg in snapshot["区段"]:
            next_id = len(rows) + 1
            rows.append({
                "id": next_id,
                "清单编号": f"MANI-{next_id:04d}",
                "配置编号": snapshot["配置编号"],
                "快照编号": snapshot["快照编号"],
                "批次开始": snapshot["批次开始"],
                "批次结束": snapshot["批次结束"],
                "区段": seg["区段"],
                "区段开始": seg["开始"],
                "区段结束": seg["结束"],
                "保存天数": seg["保存天数"],
                "配置来源": seg["配置来源"],
                "校验结论": snapshot["校验结论"]["结论"],
                "同步时间": snapshot["提交时间"],
            })
    return rows


