from __future__ import annotations

from datetime import date, timedelta
from typing import Any


def _daily_segments(start: str, end: str, retention: int, source: str) -> list[dict[str, Any]]:
    """按天展开批次区段：与分区计算快照服务的切分口径保持一致。"""
    cursor = date.fromisoformat(start)
    last = date.fromisoformat(end)
    segments: list[dict[str, Any]] = []
    while cursor <= last:
        segments.append({
            "区段": cursor.isoformat(),
            "开始": cursor.isoformat(),
            "结束": cursor.isoformat(),
            "保存天数": retention,
            "来源": "本批次新算",
            "配置来源": source,
        })
        cursor += timedelta(days=1)
    return segments


